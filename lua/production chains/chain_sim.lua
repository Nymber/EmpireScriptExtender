--[[
  chain_sim.lua - production chains for Empire: Total War.

  WHY THIS EXISTS IN LUA AT ALL
    Empire has no native concept of a building CONSUMING a commodity. Effects
    only add. And the demand-driver system that does express one good driving
    another (ddr_cotton_production, ddr_textile_production...) cannot be
    extended: those six names are string literals baked into a fixed array at
    0x014490E4, so a seventh driver would be a key with no code behind it.

    So the engine owns production, pricing, trade and display; this script owns
    STORAGE and CONSUMPTION.

    IT DOES NOT CONVERT. A Foundry already makes steel through
    commodity_prod_steel, so turning iron+coal into steel here as well would
    create every good twice - once in the engine's trade figures and once in
    our stockpile. Instead a produced good OWES its recipe inputs, and the
    stockpile pays them.

    Each turn:
      1. split production into KEPT (up to the player's target) and SOLD
      2. charge the treasury for what was kept - the engine already paid for
         it, so holding it back has to cost what selling would have earned
      3. draw each produced good's recipe inputs from the stockpile, billing
         anything short at an import markup
    See docs/STORAGE_DESIGN.md.

  DESIGN CONSTRAINTS LEARNED THE HARD WAY
    * `pcall` does NOT catch native faults. Engine conditions are C functions
      that dereference their arguments without validating, so a wrong arity or
      a wrong-scoped context is an access violation, not a Lua error. Every
      handler body goes through ESE_Protect, and only verified signatures are
      called.
    * Context is scoped. Reading faction data inside a region-scoped event
      yields silent zeros rather than an error.
    * Persistence WANTS the engine's own save_value/load_value so stockpiles
      travel inside the save. Nothing in the campaign state provides a
      game_interface, so it falls back to a file that does NOT rewind when
      the player loads an earlier save.

  STATUS: runs. Loaded by mod.lua in this folder, ticks on FactionTurnStart, and
  M.selftest() passes. What it does NOT yet have is a production source -
  derive_production() from building counts is phase 1 of the storage design
  and needs a live campaign to confirm the condition signatures.
]]--

local M = {}

