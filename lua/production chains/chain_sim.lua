-- Prefer the generated file, sitting beside this script. Returns the recipes
-- actually in force and says which source won, because silently running the
-- stale fallback is exactly the failure that wastes a playtest.
function M.load_recipes(path)
  local f = io.open(path, "rb")
  if not f then
    return M.recipes, "built-in fallback (" .. path .. " not found)"
  end
  local src = f:read("*a"); f:close()
  local chunk, err = loadstring(src, "chain_recipes")
  if not chunk then
    return M.recipes, "built-in fallback (chain_recipes.lua did not compile: " .. tostring(err) .. ")"
  end
  local ok, t = pcall(chunk)
  if not ok or type(t) ~= "table" or #t == 0 then
    return M.recipes, "built-in fallback (chain_recipes.lua produced no table)"
  end
  M.recipes = t
  return t, "chain_recipes.lua (" .. #t .. " recipes)"
end

-- Recipes must be applied in dependency order: steel before muskets, gunpowder
-- before ammunition. Sorting once at load is cheaper and clearer than assuming
-- the manifest happens to be ordered correctly.
-- Dependency order, and among equally-valid orders the one that respects
-- MANIFEST PRIORITY (earlier in chain_manifest.txt wins).
--
-- Order is not cosmetic: recipes share raw materials and allocation is greedy,
-- so whoever runs first takes what it wants. The first real run picked an
-- arbitrary valid order, naval supplies ran before muskets and ate 48 of 50
-- timber, and the musket works made 8 muskets while 88 steel sat unused.
-- Scanning FORWARD and taking the first ready recipe gives military goods
-- their inputs before naval stores, because that is the manifest's order.
function M.order_recipes(recipes)
  local produced, ordered, remaining = {}, {}, {}
  for i, r in ipairs(recipes) do remaining[i] = r end
  local guard = 0
  while #remaining > 0 and guard < 64 do
    guard = guard + 1
    local progressed = false
    for i = 1, #remaining do
      local r = remaining[i]
      local ready = true
      for input, _ in pairs(r.inputs) do
        -- an input is fine if nothing STILL PENDING produces it: either it is
        -- a raw material, or its producer has already been ordered
        for _, other in ipairs(remaining) do
          if other ~= r and other.out == input then ready = false break end
        end
        if not ready then break end
      end
      if ready then
        table.insert(ordered, r)
        produced[r.out] = true
        table.remove(remaining, i)
        progressed = true
        break        -- restart the scan so priority is re-evaluated each pick
      end
    end
    if not progressed then
      -- a cycle: ship the rest in declaration order rather than looping forever
      for _, r in ipairs(remaining) do table.insert(ordered, r) end
      ESE_Log("[chain] WARNING: recipe cycle detected, " .. #remaining .. " left unordered")
      break
    end
  end
  return ordered
end

-- ---------------------------------------------------------------- stockpiles
-- Keyed per faction so each nation has its own industry.
local function key_for(faction, good) return "chain_" .. faction .. "_" .. good end

-- The engine's own save_value/load_value would be ideal - stockpiles would
-- travel inside the save and survive a reload correctly. But `gi` is only a
-- guess until something is confirmed to provide it: the campaign Lua state
-- exposes events, conditions and a TWELVE-member effect table, and nothing
-- resembling a game_interface. So this uses the engine when it is really
-- there and falls back to a file otherwise, and SAYS WHICH.
--
-- The file fallback desynchronises if the player reloads an earlier save -
-- the stockpile does not rewind with the campaign. That is a real limitation,
-- not a detail; it is acceptable only until save_value is confirmed.
M.store = { kind = "none" }

function M.use_engine_store(gi)
  local ok = pcall(function() return gi:load_value("chain_probe", 0) end)
  if not ok then return false end
  M.store = { kind = "engine", gi = gi }
  return true
end

function M.use_file_store(path)
  local data = {}
  local f = io.open(path, "rb")
  if f then
    local src = f:read("*a"); f:close()
    local chunk = loadstring("return " .. src)
    if chunk then
      local good, t = pcall(chunk)
      if good and type(t) == "table" then data = t end
    end
  end
  M.store = { kind = "file", path = path, data = data, dirty = false }
  return true
end

function M.flush()
  local s = M.store
  if s.kind ~= "file" or not s.dirty then return end
  local parts = { "{" }
  local keys = {}
  for k in pairs(s.data) do table.insert(keys, k) end
  table.sort(keys)
  for _, k in ipairs(keys) do
    -- NEVER write a target_ key here. Targets are owned by the UI state and
    -- live in chain_targets.lua; an old chain_stock.lua may still carry some,
    -- and rewriting them from this stale copy is precisely the clobber the
    -- two-file split exists to prevent. Dropping them here also migrates an
    -- existing file the first time it is written.
    if string.sub(k, 1, 7) ~= "target_" then
      table.insert(parts, string.format("  [%q] = %d,", k, s.data[k]))
    end
  end
  table.insert(parts, "}")
  local f = io.open(s.path, "wb")
  if f then f:write(table.concat(parts, "\n")); f:close(); s.dirty = false end
end

function M.get_stock(gi, faction, good)
  local s, k = M.store, key_for(faction, good)
  if s.kind == "engine" then
    local ok, v = pcall(function() return s.gi:load_value(k, 0) end)
    if ok and type(v) == "number" then return v end
    return 0
  elseif s.kind == "file" then
    return s.data[k] or 0
  end
  return 0
end

function M.set_stock(gi, faction, good, n)
  if n < 0 then n = 0 end
  n = math.floor(n)
  local s, k = M.store, key_for(faction, good)
  if s.kind == "engine" then
    pcall(function() s.gi:save_value(k, n) end)
  elseif s.kind == "file" then
    s.data[k] = n
    s.dirty = true
  end
end

-- ------------------------------------------------- production from buildings
-- No Lua condition returns a commodity QUANTITY - of 279, the only ones that
-- mention commodities or resources are boolean. So production is DERIVED:
-- ask the engine which chain buildings we own, and look their output up in
-- chain_buildings.lua, generated from the same manifest that created them.
-- That beats reading engine memory: no addresses, survives a patch, and it
-- cannot drift from the buildings actually shipped.
M.buildings = {}

function M.load_buildings(path)
  local f = io.open(path, "rb")
  if not f then return nil, "chain_buildings.lua not found at " .. path end
  local src = f:read("*a"); f:close()
  local chunk, err = loadstring(src, "chain_buildings")
  if not chunk then return nil, "chain_buildings.lua did not compile: " .. tostring(err) end
  local ok, t = pcall(chunk)
  if not ok or type(t) ~= "table" then return nil, "chain_buildings.lua produced no table" end
  M.buildings = t
  local n = 0
  for _ in pairs(t) do n = n + 1 end
  return t, n .. " building levels"
end

